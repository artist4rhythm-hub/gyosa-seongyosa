/* ═══════════════════════════════════════════════════════════════
   📅 대한민국 법정 공휴일 (holidays-kr.js) — 공용 자료
   ───────────────────────────────────────────────────────────────
   · 학사일정 달력 표시와 관리자 «법정 공휴일 한 번에 담기» 버튼이
     같은 이 자료를 씁니다. 한 곳만 고치면 양쪽이 함께 맞습니다.
   · 설날·추석·부처님오신날(음력)과 대체공휴일은 해마다 날짜가
     달라 연도별 표에 적어 둡니다. 새 연도가 필요하면 여기에
     한 해치를 추가하면 됩니다. (신설 임시공휴일도 여기에)
   ═══════════════════════════════════════════════════════════════ */
(function(){
'use strict';

/* 해마다 같은 날짜인 공휴일 */
const FIXED = [
  { m:1,  d:1,  name:'새해 첫날' },
  { m:3,  d:1,  name:'삼일절' },
  { m:5,  d:5,  name:'어린이날' },
  { m:6,  d:6,  name:'현충일' },
  { m:8,  d:15, name:'광복절' },
  { m:10, d:3,  name:'개천절' },
  { m:10, d:9,  name:'한글날' },
  { m:12, d:25, name:'성탄절' },
];

/* 음력 기반 — 해마다 날짜가 다르다 */
const LUNAR = {
  2026:[{date:'2026-02-16',name:'설날 연휴'},{date:'2026-02-17',name:'설날'},{date:'2026-02-18',name:'설날 연휴'},
        {date:'2026-05-24',name:'부처님오신날'},{date:'2026-09-24',name:'추석 연휴'},{date:'2026-09-25',name:'추석'},{date:'2026-09-26',name:'추석 연휴'}],
  2027:[{date:'2027-02-06',name:'설날 연휴'},{date:'2027-02-07',name:'설날'},{date:'2027-02-08',name:'설날 연휴'},
        {date:'2027-05-13',name:'부처님오신날'},{date:'2027-09-14',name:'추석 연휴'},{date:'2027-09-15',name:'추석'},{date:'2027-09-16',name:'추석 연휴'}],
  2028:[{date:'2028-01-26',name:'설날 연휴'},{date:'2028-01-27',name:'설날'},{date:'2028-01-28',name:'설날 연휴'},
        {date:'2028-05-02',name:'부처님오신날'},{date:'2028-10-02',name:'추석 연휴'},{date:'2028-10-03',name:'추석'},{date:'2028-10-04',name:'추석 연휴'}],
};

/* 대체공휴일·신설 임시공휴일 — 정부 발표에 따라 연도별로 적는다 */
const SUBSTITUTE = {
  2026:[{date:'2026-03-02',name:'삼일절 대체휴일'},{date:'2026-05-25',name:'대체공휴일'},{date:'2026-08-17',name:'광복절 대체휴일'}],
};

const ymd = (y,m,d)=>`${y}-${String(m).padStart(2,'0')}-${String(d).padStart(2,'0')}`;

window.KRHOL = {
  FIXED, LUNAR, SUBSTITUTE,
  /* {날짜:이름} 지도 */
  getMap(year){
    const map = {};
    FIXED.forEach(h=>{ map[ymd(year,h.m,h.d)] = h.name; });
    (LUNAR[year]||[]).forEach(h=>{ map[h.date] = h.name; });
    (SUBSTITUTE[year]||[]).forEach(h=>{ map[h.date] = h.name; });
    return map;
  },
  /* 음력 자료까지 갖춘 연도인가 */
  has(year){ return !!LUNAR[year]; },
  /* 자료가 있는 연도들 */
  years(){ return Object.keys(LUNAR).map(Number).sort(); },
};
})();
